package chapter2operators;

public class L6ShiftOperator {
    static void main(String[] args) {

        int a = 10 << 3; //left shift // 10 * (2 ** 3)
        System.out.println(a);

        int b = 10 >> 2; // right shift // 10 * (2 ** 2)
        System.out.println(b);

    }
}

