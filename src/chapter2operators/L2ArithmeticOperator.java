package chapter2operators;

public class L2ArithmeticOperator {
    static void main(String[] args) {
        int a = 17;
        int b = 4;

        int add = a + b;
        System.out.println(add);

        int sub = a - b;
        System.out.println(sub);

        int mul = a * b;
        System.out.println(mul);

        int div = a / b;
        System.out.println(div);

        int mod = a % b;
        System.out.println(mod);

        int ramdomCalculation = (23 + 8) / 3;
//        int ramdomCalculation = 23 + 3*3 + 20/3;
        System.out.println(ramdomCalculation);

        System.out.println(2 + 6 + "KyiMin" + (3 + 4));

    }
}
